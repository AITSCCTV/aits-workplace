// Fixed messages only: never persist provider messages, request bodies, or tokens.
export function studioPublishingError(code) {
  if (code === 190) return 'การเชื่อมต่อหมดอายุหรือถูกยกเลิก ให้ผู้ดูแลเชื่อมต่อบัญชีใหม่แล้วรีเฟรช';
  if (code === 10 || code === 200) return 'บัญชีไม่มีสิทธิ์เผยแพร่ ให้ผู้ดูแลตรวจสอบสิทธิ์เพจและแอปแล้วเชื่อมต่อใหม่';
  if ([4, 17, 32, 613].includes(code)) return 'แพลตฟอร์มจำกัดจำนวนคำขอ กรุณารอสักครู่ก่อนลองใหม่';
  if (code === 100) return 'แพลตฟอร์มไม่ยอมรับข้อมูลโพสต์ ให้ผู้ดูแลตรวจสอบรูปภาพและการตั้งค่าบัญชี';
  return 'แพลตฟอร์มปฏิเสธการเผยแพร่ ให้ผู้ดูแลตรวจสอบการเชื่อมต่อและสิทธิ์ก่อนลองใหม่';
}
